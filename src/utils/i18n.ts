type TranslationKey = keyof typeof translations.vi;

export function t(key: TranslationKey, lang: Language, params?: Record<string, string | number>): string {
  let text: string = translations[lang][key] || translations.vi[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}
